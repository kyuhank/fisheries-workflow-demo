#!/usr/bin/env Rscript
# Host fixtures use temporary files and explicit transport/runtime doubles.
script <- sub("^--file=", "", commandArgs()[startsWith(commandArgs(), "--file=")][[1L]])
root <- normalizePath(file.path(dirname(script), ".."), mustWork = TRUE)
setwd(root)
source('R/sources.R');source('R/inputs.R');source('R/workflow.R');source('scripts/release.R');source('R/local.R')
fixture <- tempfile('local-root-');workspace <- tempfile('local-workspace-');dir.create(fixture)
dir.create(file.path(fixture,'workflow'));stopifnot(file.copy('workflow/jobs.json',file.path(fixture,'workflow/jobs.json')))
json_write(list(output_sha256=paste(rep('a',64),collapse='')),file.path(fixture,'data/public-data.json'))
writeLines('<!doctype html><script id="demo-payload" type="application/json">{"cloud":{"url":"https://example.invalid/api","repository":"kyuhank/fisheries-workflow-demo"},"saved":{"records":{}}}</script>',file.path(fixture,'index.html'))
backend <- local_new(fixture,workspace,8765L,verify=FALSE)
page <- local_page(backend);payload <- jsonlite::fromJSON(regmatches(page,regexec('<script id="demo-payload" type="application/json">(.*?)</script>',page,perl=TRUE))[[1]][[2]],simplifyVector=FALSE)
stopifnot(payload$cloud$provider=='local',payload$cloud$url=='http://127.0.0.1:8765/api')
stopifnot(local_api(backend,'GET','/info')$configured)
capability <- local_api(backend,'POST','/session',body=list())
query <- list(session=capability$id);authorization <- paste('Bearer',capability$token)
session <- local_authenticate(backend,capability$id,authorization)
reject <- function(expr)inherits(tryCatch(force(expr),error=identity),'error')
stopifnot(reject(local_api(backend,'GET','/state',query,authorization='Bearer wrong')))
stopifnot(reject(local_query('session=a&session=b')))
stopifnot(identical(local_query('?session=a&after=0'), local_query('session=a&after=0')), !length(local_query('?')))
stopifnot(reject(local_api(backend,'GET','/output',c(query,list(job='../../private')),authorization=authorization)))
body <- list(start='cpue_a',scope='job',handover='manual',settings=list(last_year=2022L,min_hooks_a=0,growth_rate_2=.35,mse=TRUE,mse_buffer=.6))
stopifnot(local_settings(backend,body)$last_year==2022)
wrong <- body;wrong$settings$last_year<-2023;stopifnot(reject(local_settings(backend,wrong)))
wrong <- body;wrong$settings['mse']<-list(NULL);stopifnot(reject(local_settings(backend,wrong)))
wrong <- body;wrong['scope']<-list(NULL);stopifnot(reject(local_settings(backend,wrong)))
wrong <- body;wrong$start<-'unknown';stopifnot(reject(local_settings(backend,wrong)))
request <- list(id=local_uuid(),status='running');directory<-file.path(session$directory,'requests',request$id);dir.create(directory,recursive=TRUE)
json_write(list(id=request$id),file.path(session$directory,'current.json'))
json_write(list(transfer_count=0L,connected=FALSE,cancelled=FALSE),file.path(directory,'control.json'))
state <- list(records=json_object())
event <- list(job='cpue_a',state='handover',boundary='cpue',group=list('cpue_a','cpue_b'))
local_event(directory,event,state,1L,request)
confirm <- list(request_id=request$id,transfer_count=0L,connect=FALSE)
one <- local_transfer(session,confirm);two <- local_transfer(session,confirm)
stopifnot(one$transfer_count==1L,!one$replay,two$replay,two$transfer_count==1L)
local_event(directory,list(job='cpue_a',state='received'),state,2L,request)
local_event(directory,event,state,3L,request)
old <- local_transfer(session,confirm);stopifnot(old$transfer_count==1L,old$replay)
future <- confirm;future$transfer_count <- 2L;stopifnot(reject(local_transfer(session,future)))
confirm$transfer_count<-1L;confirm$connect<-TRUE
connected <- local_transfer(session,confirm);stopifnot(connected$connected,connected$transfer_count==2L)
stopifnot(local_handover(directory,1L)$connected)
update <- local_api(backend,'GET','/state',c(query,list(after='1')),authorization=authorization)
stopifnot(length(update$events)==2L,update$events[[1]]$id==2L,update$events[[2]]$event$transfer_count==1L)
request_http <- list(HTTP_HOST='127.0.0.1:8765',HTTP_ORIGIN='https://foreign.invalid',REQUEST_METHOD='POST',PATH_INFO='/api/session',CONTENT_TYPE='application/json')
stopifnot(local_http(backend,request_http)$status==403L)
request_http$HTTP_ORIGIN<-backend$origin;request_http$HTTP_HOST<-'foreign.invalid:8765'
stopifnot(local_http(backend,request_http)$status==403L)
request_http$HTTP_HOST<-'127.0.0.1:8765';request_http$REQUEST_METHOD<-'GET';request_http$PATH_INFO<-'/../private'
stopifnot(local_http(backend,request_http)$status==404L)
request_http$PATH_INFO<-'/'
stopifnot(local_http(backend,request_http)$status==200L)
stopifnot(reject(local_api(backend,'POST','/reset',query,body=list(),authorization=authorization)))
request$status<-'complete';json_write(request,file.path(directory,'status.json'))
invisible(local_api(backend,'POST','/reset',query,body=list(),authorization=authorization))
stopifnot(reject(local_authenticate(backend,capability$id,authorization)))
# A previous unfinished request is preserved and prevents silent reuse of its workspace.
request$status<-'running';json_write(request,file.path(directory,'status.json'))
stopifnot(reject(local_new(fixture,workspace,8766L,verify=FALSE)))
output <- file.path(session$directory,'results');folder<-file.path(output,'cpue_a');dir.create(folder,recursive=TRUE)
json_write(list(answer=42),file.path(folder,'output.json'))
writeBin(charToRaw('<html>Line one\nLine two</html>\n'),file.path(folder,'report.html'))
writeBin(charToRaw('%PDF-local-output-fixture'),file.path(folder,'report.pdf'))
record <- list(job='cpue_a',outputs=setNames(lapply(c('output.json','report.html','report.pdf'),function(name)file_sha256(file.path(folder,name))),c('output.json','report.html','report.pdf')))
json_write(list(records=list(cpue_a=record)),file.path(output,'state.json'))
returned <- local_output(session,'cpue_a')
stopifnot(identical(digest::digest(charToRaw(returned$html),algo='sha256',serialize=FALSE),record$outputs[['report.html']]))
container <- paste(rep('a',64),collapse='');image <- paste0('sha256:',paste(rep('b',64),collapse=''))
receipt <- list(job='cpue_a',container_id=container,image_id=image,output=value_sha256(normalizePath(folder)))
json_write(receipt,file.path(folder,'active-container-inside-job.json'))
actual <- list(Image=image,Config=list(Labels=list('org.fisheries-workflow.job'='cpue_a','org.fisheries-workflow.output'='foreign')))
removed <- FALSE
# Docker inspection/removal is replaced with an explicit ownership fixture.
runtime_process <- function(...)list(status=0L,stdout=json_encode(list(actual)))
runtime_checked <- function(...) {removed<<-TRUE;''}
stopifnot(reject(local_cleanup_containers(output,backend$config$jobs)),!removed)
actual$Config$Labels[['org.fisheries-workflow.output']]<-receipt$output
local_cleanup_containers(output,backend$config$jobs);stopifnot(removed)
cat('Container cleanup fixture refused foreign labels and accepted only the recorded local job identity.\n')
cat('Local API fixtures passed: capabilities, origin/host/path isolation, settings, cursor events, manual-transfer replay/connect, reset and unfinished-run custody. No HTTP listener, fork, Docker or models started.\n')
unlink(c(fixture,workspace),recursive=TRUE)
